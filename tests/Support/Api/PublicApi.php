<?php

declare(strict_types=1);

namespace Domm98CZ\Color\Tests\Support\Api;

/**
 * Describes the public API of the library as stable text lines: every class, interface and enum
 * outside `*\Internal\*` and without `@internal`, with its public constants, enum cases, public
 * properties and public methods (parameter names, types and defaults included, since named
 * arguments make parameter names part of the API).
 *
 * The text is compared with a committed snapshot, so every change of the public API is visible in
 * review. Regenerate it with `php tools/api-snapshot.php`.
 */
final class PublicApi
{
    private const string NAMESPACE = 'Domm98CZ\\Color\\';

    /** @var list<string> implied by `enum` or by extending an exception */
    private const array IMPLIED_INTERFACES = [\UnitEnum::class, \BackedEnum::class, \Stringable::class, \Throwable::class];

    /** @var list<string> generated by PHP for every backed enum */
    private const array ENUM_METHODS = ['cases', 'from', 'tryFrom'];

    /**
     * @return list<class-string> every class-like declared under the source directory, sorted
     */
    public static function declarations(string $sourceDirectory): array
    {
        $classes = [];
        $files = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($sourceDirectory, \FilesystemIterator::SKIP_DOTS));
        foreach ($files as $file) {
            if (!$file instanceof \SplFileInfo || $file->getExtension() !== 'php') {
                continue;
            }
            $relative = \substr($file->getPathname(), \strlen(\rtrim($sourceDirectory, '/')) + 1, -4);
            $name = self::NAMESPACE . \str_replace('/', '\\', $relative);
            if (\class_exists($name) || \interface_exists($name) || \enum_exists($name)) {
                $classes[] = $name;
            }
        }
        \sort($classes);

        return $classes;
    }

    /**
     * @param \ReflectionClass<object> $class
     */
    public static function isInternal(\ReflectionClass $class): bool
    {
        return \str_contains($class->getName(), '\\Internal\\') || self::hasTag($class->getDocComment(), 'internal');
    }

    /**
     * @return list<string>
     */
    public static function describe(string $sourceDirectory): array
    {
        $lines = [];
        foreach (self::declarations($sourceDirectory) as $name) {
            $class = new \ReflectionClass($name);
            if (self::isInternal($class)) {
                continue;
            }
            \array_push($lines, ...self::describeClass($class));
        }

        return $lines;
    }

    /**
     * @param \ReflectionClass<object> $class
     *
     * @return list<string>
     */
    private static function describeClass(\ReflectionClass $class): array
    {
        $lines = [self::short($class->getName()) . ': ' . self::kind($class) . self::markers($class->getDocComment())];

        $parents = [];
        $parent = $class->getParentClass();
        if ($parent !== false) {
            $parents[] = 'extends ' . self::short($parent->getName());
        }
        $interfaces = $class->getInterfaceNames();
        \sort($interfaces);
        foreach ($interfaces as $interface) {
            if (!\in_array($interface, self::IMPLIED_INTERFACES, true)) {
                $parents[] = 'implements ' . self::short($interface);
            }
        }
        foreach ($parents as $line) {
            $lines[] = '  ' . $line;
        }

        foreach ($class->getReflectionConstants(\ReflectionClassConstant::IS_PUBLIC) as $constant) {
            if ($constant->getDeclaringClass()->getName() !== $class->getName() || self::hasTag($constant->getDocComment(), 'internal')) {
                continue;
            }
            if ($constant->isEnumCase()) {
                $value = $constant->getValue();
                $lines[] = '  case ' . $constant->getName() . ($value instanceof \BackedEnum ? ' = ' . \var_export($value->value, true) : '');
                continue;
            }
            $lines[] = '  const ' . $constant->getName() . ' = ' . self::export($constant->getValue());
        }

        foreach ($class->getProperties(\ReflectionProperty::IS_PUBLIC) as $property) {
            if ($property->getDeclaringClass()->getName() !== $class->getName() || $class->isEnum()) {
                continue;
            }
            $lines[] = '  property ' . ($property->isStatic() ? 'static ' : '') . ($property->isReadOnly() ? 'readonly ' : '')
                . self::type($property->getType(), $property->getDeclaringClass()->getName()) . ' $' . $property->getName();
        }

        $methods = $class->getMethods(\ReflectionMethod::IS_PUBLIC);
        \usort($methods, static fn(\ReflectionMethod $a, \ReflectionMethod $b): int => $a->getName() <=> $b->getName());
        foreach ($methods as $method) {
            if ($method->getDeclaringClass()->getName() !== $class->getName()
                || self::hasTag($method->getDocComment(), 'internal')
                || ($class->isEnum() && \in_array($method->getName(), self::ENUM_METHODS, true))) {
                continue;
            }
            $lines[] = '  method ' . self::signature($method) . self::markers($method->getDocComment());
        }

        return $lines;
    }

    /**
     * @param \ReflectionClass<object> $class
     */
    private static function kind(\ReflectionClass $class): string
    {
        if ($class->isInterface()) {
            return 'interface';
        }
        $name = $class->getName();
        if (\enum_exists($name)) {
            $backing = (new \ReflectionEnum($name))->getBackingType();

            return 'enum' . ($backing === null ? '' : ': ' . $backing);
        }

        return ($class->isAbstract() ? 'abstract ' : '') . ($class->isFinal() ? 'final ' : '') . ($class->isReadOnly() ? 'readonly ' : '') . 'class';
    }

    private static function signature(\ReflectionMethod $method): string
    {
        $parameters = [];
        foreach ($method->getParameters() as $parameter) {
            $text = self::type($parameter->getType(), $method->getDeclaringClass()->getName());
            $text .= ($text === '' ? '' : ' ') . ($parameter->isPassedByReference() ? '&' : '') . ($parameter->isVariadic() ? '...' : '') . '$' . $parameter->getName();
            if ($parameter->isPromoted()) {
                $text = 'promoted ' . $text;
            }
            if ($parameter->isDefaultValueAvailable()) {
                $text .= ' = ' . self::defaultValue($parameter);
            }
            $parameters[] = $text;
        }
        $return = $method->hasReturnType() ? ': ' . self::type($method->getReturnType(), $method->getDeclaringClass()->getName()) : '';

        return ($method->isStatic() ? 'static ' : '') . ($method->isAbstract() && !$method->getDeclaringClass()->isInterface() ? 'abstract ' : '')
            . $method->getName() . '(' . \implode(', ', $parameters) . ')' . $return;
    }

    private static function defaultValue(\ReflectionParameter $parameter): string
    {
        if (\preg_match('~ = (.*) \]$~s', (string) $parameter, $match) === 1) {
            return self::short(\str_replace('\\' . self::NAMESPACE, '', $match[1]));
        }

        return '?'; // @codeCoverageIgnore
    }

    private static function type(?\ReflectionType $type, string $declaringClass): string
    {
        if ($type === null) {
            return '';
        }

        // PHP 8.5 reflection resolves `self` to the class name while older versions keep `self`.
        return self::short((string) \preg_replace('~(?<![\w\\\\])self(?![\w\\\\])~', $declaringClass, (string) $type));
    }

    private static function short(string $name): string
    {
        return \str_replace(self::NAMESPACE, '', $name);
    }

    private static function export(mixed $value): string
    {
        if ($value instanceof \UnitEnum) {
            return self::short($value::class) . '::' . $value->name;
        }
        if (\is_float($value)) {
            return \var_export($value, true);
        }
        if (\is_array($value)) {
            $items = [];
            $list = \array_is_list($value);
            foreach ($value as $key => $item) {
                $items[] = ($list ? '' : \var_export($key, true) . ' => ') . self::export($item);
            }

            return '[' . \implode(', ', $items) . ']';
        }

        return \var_export($value, true);
    }

    private static function markers(string|false $comment): string
    {
        $markers = [];
        foreach (['experimental', 'deprecated'] as $tag) {
            if (self::hasTag($comment, $tag)) {
                $markers[] = '@' . $tag;
            }
        }

        return $markers === [] ? '' : ' [' . \implode(', ', $markers) . ']';
    }

    private static function hasTag(string|false $comment, string $tag): bool
    {
        return $comment !== false && \preg_match('~^\s*\*\s*@' . $tag . '\b~m', $comment) === 1;
    }
}
